"""Reproducible floating-point diagnostics for the full water-profile objective.

This is not a validated-numerics module. It scans stated finite windows and
does not certify a global integer maximum. Gaussian feature truncation,
quadrature agreement and algebraic residuals are reported separately.
No figures or PDFs are generated by this driver.

Run from any directory:
    python scripts/profile_optimum_study.py
"""
from __future__ import annotations

import argparse
import csv
import json
import math
import os
from pathlib import Path
import platform

for _name in ("OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "OMP_NUM_THREADS"):
    os.environ.setdefault(_name, "1")

import numpy as np
from numpy.polynomial.legendre import leggauss

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
GENERATED = ROOT / "generated"
STATUS = "FLOAT_DIAGNOSTIC_NOT_CERTIFICATE"
FIELDS = [
    "study_kind", "D", "V", "dw", "r", "m", "nodes_per_patch", "features",
    "lambda_top_point", "profile_objective_point", "plant_beta_point",
    "scalar_objective_point", "water_max_point", "water_mean_point",
    "dv", "B", "profile_margin_point", "residual_l2", "iterations",
    "feature_tail_bound_float", "status",
]


def envelope_reference(D: float, V: float, nodes: int) -> dict:
    """Independent smooth-envelope quadrature; no coefficient is fitted."""
    z, w = leggauss(nodes)
    x, weights = z * D / 2, w * D / 2
    rootw = np.sqrt(weights)
    distance = x[:, None] - x[None, :]
    matrix = np.exp(-distance * distance / 2) / math.sqrt(2 * math.pi)
    matrix *= rootw[:, None] * rootw[None, :]
    values, vectors = np.linalg.eigh(matrix)
    rho = float(values[-1])
    vector = vectors[:, -1]
    if np.sum(vector) < 0:
        vector = -vector
    endpoint = float(
        np.dot(np.exp(-(D / 2 - x) ** 2 / 2) / math.sqrt(2 * math.pi), vector * rootw) / rho
    )
    theta, delta = V / D, D - V
    c_trace = -theta * delta / D * rho * (D * endpoint * endpoint - 1)
    c_integral = -theta * delta / D * float(vector @ (-(distance * distance) * matrix) @ vector)
    return {
        "D": D, "V": V, "nodes": nodes, "rho_envelope_point": rho,
        "beta_infinity_point": 1 - theta * rho,
        "c_D_boundary_trace_point": c_trace,
        "c_D_double_integral_point": c_integral,
        "coefficient_identity_difference": abs(c_trace - c_integral),
        "status": STATUS,
    }


def gaussian_tail_bound_float(D: float, V: float, features: int) -> float:
    """Analytic positive-tail majorant evaluated in float, not outward rounded.

    On |x|<=D/2, discard exp(-x^2)<=1 and bound the feature trace by a
    geometric series starting at k=p. This does not bound quadrature error.
    """
    a = (D / 2) ** 2
    ratio = a / (features + 1)
    if ratio >= 1:
        raise ValueError("Feature count must have (D/2)^2 < p+1.")
    return V / math.sqrt(2 * math.pi) * math.exp(features * math.log(a) - math.lgamma(features + 1)) / (1 - ratio)


def diagnostic_case(
    D: float, V: float, dw: float, r: float, m: int,
    nodes_per_patch: int, features: int, dv: float, B: float,
) -> dict:
    ell = V / m
    gap = (D - V) / (m - 1)
    nodes, weights = leggauss(nodes_per_patch)
    local = nodes * ell / 2
    centres = -D / 2 + ell / 2 + np.arange(m) * (ell + gap)
    x = (centres[:, None] + local[None, :]).ravel()
    cell_weights = np.tile(weights * ell / 2, m)

    # Stable cosh(t)-cosh(s)=2*sinh((t+s)/2)*sinh((t-s)/2).
    # This avoids loss from subtracting two values close to one at large m.
    t = ell / (2 * math.sqrt(dw))
    s = local / math.sqrt(dw)
    local_water = 2 * np.sinh((t + s) / 2) * np.sinh((t - s) / 2) / math.cosh(t)
    water = np.tile(local_water, m)
    qmax = 2 * math.sinh(t / 2) ** 2 / math.cosh(t)
    # A short Taylor series avoids cancellation in the diagnostic mean.
    if abs(t) < 0.05:
        t2 = t * t
        qmean = t2 * (1 / 3 + t2 * (-2 / 15 + t2 * (17 / 315 + t2 * (-62 / 2835 + t2 * 1382 / 155925))))
    else:
        qmean = 1 - math.tanh(t) / t

    feature = np.empty((x.size, features))
    feature[:, 0] = np.sqrt(cell_weights) * (2 * math.pi) ** (-0.25) * np.exp(-x * x / 2)
    for k in range(1, features):
        feature[:, k] = feature[:, k - 1] * x / math.sqrt(k)
    gram = feature.T @ feature
    eigvals, eigvecs = np.linalg.eigh(gram)
    rho = float(eigvals[-1])
    vector = feature @ eigvecs[:, -1] / math.sqrt(rho)
    if np.sum(vector) < 0:
        vector = -vector

    def matvec(v):
        return feature @ (feature.T @ v) + r * water * v

    for iteration in range(1, 5001):
        product = matvec(vector)
        vector = product / np.linalg.norm(product)
        product = matvec(vector)
        value = float(vector @ product)
        residual = float(np.linalg.norm(product - value * vector))
        if residual <= 3e-15 * max(1, abs(value)):
            break
    else:
        raise ArithmeticError(f"Power iteration did not converge for D={D},r={r},m={m}.")
    profile = 1 - value
    return dict(
        D=D, V=V, dw=dw, r=r, m=m, nodes_per_patch=nodes_per_patch,
        features=features, lambda_top_point=value,
        profile_objective_point=profile, plant_beta_point=1 - rho,
        scalar_objective_point=1 - rho - r * qmax,
        water_max_point=qmax, water_mean_point=qmean, dv=dv, B=B,
        profile_margin_point=B + dv * profile, residual_l2=residual,
        iterations=iteration,
        feature_tail_bound_float=gaussian_tail_bound_float(D, V, features),
        status=STATUS,
    )


def number(value):
    return format(value, ".17g") if isinstance(value, float) else value


def dense_crosscheck(D, V, dw, r, m, reference):
    """Check features/power iteration against a dense kernel and eigvalsh."""
    ell, gap = V / m, (D - V) / (m - 1)
    nodes, weights = leggauss(8)
    local = nodes * ell / 2
    centres = -D / 2 + ell / 2 + np.arange(m) * (ell + gap)
    x = (centres[:, None] + local[None, :]).ravel()
    rootw = np.sqrt(np.tile(weights * ell / 2, m))
    distance = x[:, None] - x[None, :]
    matrix = np.exp(-distance * distance / 2) / math.sqrt(2 * math.pi)
    matrix *= rootw[:, None] * rootw[None, :]
    t, s = ell / (2 * math.sqrt(dw)), local / math.sqrt(dw)
    water = np.tile(2 * np.sinh((t + s) / 2) * np.sinh((t - s) / 2) / math.cosh(t), m)
    matrix[np.diag_indices_from(matrix)] += r * water
    point = 1 - float(np.linalg.eigvalsh(matrix)[-1])
    difference = abs(point - reference)
    if difference >= 3e-14:
        raise ArithmeticError("Dense-kernel and feature/power diagnostics disagree.")
    return dict(D=D, r=r, m=m, direct_kernel_eigvalsh_point=point,
                feature_power_point=reference, absolute_difference=difference, status=STATUS)


def tex_scientific(value):
    if value == 0:
        return "$0$"
    mantissa, exponent = format(value, ".2e").split("e")
    return f"${mantissa}\\times10^{{{int(exponent)}}}$"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spans", nargs="+", type=float, default=[4.0, 6.0])
    parser.add_argument("--ratios", nargs="+", type=float, default=[3.0, 6.0, 12.0, 24.0, 48.0])
    parser.add_argument("--V", type=float, default=2.0)
    parser.add_argument("--dw", type=float, default=1.0)
    parser.add_argument("--dv", type=float, default=0.6)
    parser.add_argument("--B", type=float, default=0.45)
    parser.add_argument("--features", type=int, default=48)
    args = parser.parse_args(argv)
    if args.V <= 0 or args.dw <= 0 or any(D <= args.V for D in args.spans) or any(r <= 0 for r in args.ratios):
        parser.error("Require positive parameters and D>V.")
    DATA.mkdir(exist_ok=True)
    GENERATED.mkdir(exist_ok=True)
    rows, summaries, references, cache = [], [], [], {}

    def evaluate(D, r, m, nodes=8, features=None, kind="local_scan"):
        p = features or args.features
        key = (D, r, m, nodes, p)
        if key not in cache:
            cache[key] = diagnostic_case(D, args.V, args.dw, r, m, nodes, p, args.dv, args.B)
            rows.append(dict(study_kind=kind, **cache[key]))
        return cache[key]

    for D in args.spans:
        envelope = envelope_reference(D, args.V, 180)
        refined = envelope_reference(D, args.V, 240)
        references.append(dict(coarse=envelope, refined=refined))
        c = refined["c_D_boundary_trace_point"]
        beta_inf = refined["beta_infinity_point"]
        bav = args.V ** 2 / (12 * args.dw)
        scale = 2 * bav / c
        value_scale = c * c / (4 * bav)
        for r in args.ratios:
            centre = scale * r
            half_width = max(6, math.ceil(0.15 * centre))
            lower, upper = max(2, math.floor(centre) - half_width), math.ceil(centre) + half_width
            if r == 12 and args.V == 2 and args.dw == 1 and D in (4, 6):
                lower, upper = 30, 80
            scan = [evaluate(D, r, m) for m in range(lower, upper + 1)]
            winner = max(scan, key=lambda row: row["profile_objective_point"])
            mstar = winner["m"]
            if mstar in (lower, upper):
                raise ArithmeticError("Diagnostic winner reached a scan boundary; enlarge the stated window.")
            neighbours = [evaluate(D, r, m, 16, kind="node_refinement") for m in range(max(2, mstar - 2), mstar + 3)]
            best = next(row for row in neighbours if row["m"] == mstar)
            close = [row for row in neighbours if abs(row["m"] - mstar) == 1]
            gap_point = min(best["profile_objective_point"] - row["profile_objective_point"] for row in close)
            if any(row["profile_objective_point"] > best["profile_objective_point"] for row in neighbours):
                raise ArithmeticError("Node refinement changed the diagnostic local winner.")
            features_check = [evaluate(D, r, mstar, 16, p, "feature_refinement") for p in sorted({max(16, args.features - 8), args.features + 8})]
            node_diff = abs(best["profile_objective_point"] - winner["profile_objective_point"])
            feature_diff = max(abs(row["profile_objective_point"] - best["profile_objective_point"]) for row in features_check)
            summary = dict(
                D=D, r=r, scan_min=lower, scan_max=upper, local_winner=mstar,
                profile_objective_point=best["profile_objective_point"],
                profile_margin_point=best["profile_margin_point"],
                adjacent_gap_point=gap_point, node_refinement_difference=node_diff,
                feature_refinement_difference=feature_diff,
                m_over_r=mstar / r, predicted_profile_count_scale=scale,
                predicted_scalar_count_scale=1.5 * scale,
                rescaled_optimal_value_point=r * (best["profile_objective_point"] - beta_inf),
                predicted_profile_value_scale=value_scale,
                predicted_scalar_value_scale=value_scale / 1.5,
                largest_algebraic_residual=max(row["residual_l2"] for row in neighbours),
                status=STATUS,
            )
            summaries.append(summary)
            print(f"D={D:g},r={r:g},window=[{lower},{upper}]: local m={mstar}; diagnostic only", flush=True)

    with (DATA / "profile_optimum_diagnostics.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=FIELDS)
        writer.writeheader()
        writer.writerows({key: number(row[key]) for key in FIELDS} for row in rows)
    dense_checks = []
    for row in summaries:
        if row["r"] == 12 and row["local_winner"] * 8 <= 800:
            reference = evaluate(row["D"], row["r"], row["local_winner"])
            dense_checks.append(dense_crosscheck(row["D"], args.V, args.dw, row["r"],
                                                row["local_winner"], reference["profile_objective_point"]))
    metadata = dict(
        status=STATUS, scope="Finite-window floating-point scans only; not continuous enclosures or global integer certificates.",
        python=platform.python_version(), numpy=np.__version__, parameters=vars(args),
        rows=len(rows), envelope_references=references, local_winners=summaries,
        independent_dense_crosscheck=dense_checks,
        methods=dict(
            operator="K_p+r*diag(z_m), where K_p is a positive Taylor-monomial Gaussian feature truncation",
            quadrature="Gauss-Legendre on each exact equal-length patch,8 nodes then16 in winner neighbourhoods",
            residual="Euclidean residual of the weighted finite quadrature matrix",
            feature_tail="Analytic continuous positive-tail formula evaluated in float; not outward rounded; excludes quadrature error",
            interpretation="Residual and refinement agreement are diagnostics, never a continuous error certificate",
        ),
    )
    (DATA / "profile_optimum_diagnostics.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")

    caption = (r"\caption{Numerical diagnostics on finite windows for the profile objective $P_m(r)$, with "
               + f"$V={args.V:g}$, $d_w={args.dw:g}$ and $r=12$. "
               + f"The initial calculations use eight Gauss nodes per patch and {args.features} Gaussian features. "
               + f"Near each local maximum, we repeat them with sixteen nodes and {max(16,args.features-8)}/{args.features+8} features. "
               + "The values and refinement differences are floating-point diagnostics; they do not enclose the continuous problem or certify a global integer maximum.}")
    tex = [r"\begin{table}[htbp]", r"\centering\small", caption,
           r"\label{tab:profile_optimum_diagnostics}", r"\begin{tabular}{llllll}", r"\toprule",
           r"$D$ & Local $m$ & $P_m(12)$ & Adjacent gap & Node check & Feature check\\", r"\midrule"]
    for row in summaries:
        if row["r"] == 12:
            tex.append(f"{row['D']:g} & {row['local_winner']} & {row['profile_objective_point']:.12f} & {tex_scientific(row['adjacent_gap_point'])} & {tex_scientific(row['node_refinement_difference'])} & {tex_scientific(row['feature_refinement_difference'])}" + r"\\")
    tex += [r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
            r"\begin{table}[htbp]", r"\centering\small",
            r"\caption{Scaling diagnostics on the stated finite windows, with the water profile retained. The text gives the limiting constants for $m/r$ and $r(P_m-\beta_\infty)$. These rows do not certify a global maximiser at a fixed ratio.}",
            r"\label{tab:profile_optimum_scaling}", r"\begin{tabular}{llllll}", r"\toprule",
            r"$D$ & $r$ & Window & Local $m$ & $m/r$ & $r(P_m-\beta_\infty)$\\", r"\midrule"]
    for row in summaries:
        tex.append(f"{row['D']:g} & {row['r']:g} & [{row['scan_min']},{row['scan_max']}] & {row['local_winner']} & {row['m_over_r']:.5f} & {row['rescaled_optimal_value_point']:.7f}" + r"\\")
    tex += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    (GENERATED / "profile_optimum_diagnostics.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")
    print(json.dumps(dict(rows=len(rows), outputs=["data/profile_optimum_diagnostics.csv", "data/profile_optimum_diagnostics.json", "generated/profile_optimum_diagnostics.tex"], status=STATUS)))
    return dict(experiments={"profile_optimum_diagnostics": rows}, checks=metadata)


if __name__ == "__main__":
    main()
