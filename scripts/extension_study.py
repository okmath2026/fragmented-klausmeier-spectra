"""Reproducible spatial-water, broad-kernel and finite-rank certificates.

Numerical trial preparation and vector figures use NumPy/ReportLab. All proof
endpoints are generated by separate standard-library validated modules.
The complete three-part run also regenerates the coupled optimum study.
"""
import os
os.environ.setdefault('OPENBLAS_NUM_THREADS','1')
os.environ.setdefault('OMP_NUM_THREADS','1')
import argparse,csv,json
from decimal import Decimal
from fractions import Fraction
from spectral_study import ROOT,DATA,FIG,TABLE,csvfile,table,plot,decimal_display,scientific_upper
from validated_gaussian import _Intervals


def read_rows(name):
    with (DATA/(name+'.csv')).open(newline='',encoding='utf-8') as stream:
        return list(csv.DictReader(stream))


def rational_display(value,places=8,upper=False):
    value=Fraction(value);bounds=_Intervals(60).fraction(value,value)
    return decimal_display(bounds[1 if upper else 0],places,upper)


def weighted_study():
    from weighted_water_trial import weighted_water_trial
    from validated_weighted_water import (weighted_water_certificate,
        weighted_scalar_comparison,weighted_water_self_check)
    from validated_peaks import fragment_certificate
    source=json.loads((DATA/'peak_vectors.json').read_text())
    vector=next(v for v in source if v['D']=='4' and v['m']==2 and v['cells_per_patch']==4)
    direct=fragment_certificate('4',2,4,vector['q'],60)
    rows=[];vectors=[];audits=[]
    for r in (2,4,8,16,32):
        q,diagnostic=weighted_water_trial('4',2,r)
        record,audit=weighted_water_certificate('4',2,r,q,return_details=True)
        comparison=weighted_scalar_comparison(record,direct['beta_lower'],direct['beta_upper'])
        rows.append(dict(**record,**comparison,**diagnostic))
        vectors.append(dict(D='4',V='2',m=2,cells_per_patch=r,dv='.5',dw='1',Amax='1.8',R='4',B='.45',precision=60,q=q))
        audits.append(audit)
    check=weighted_water_self_check('4',2,8,vectors[2]['q'])
    assert rows[2]['strict_weighted_improvement'] is True
    assert Decimal(rows[2]['cw_upper'])<Decimal('.871655')
    assert Decimal(rows[2]['scalar_margin_upper'])<Decimal('-.05192687')
    assert Fraction(rows[2]['kernel_eta_radius_strict'])>Fraction('.03')
    (DATA/'weighted_water_vectors.json').write_text(json.dumps(vectors,indent=2)+'\n',encoding='ascii')
    (DATA/'weighted_water_audits.json').write_text(json.dumps(dict(cases=audits,self_check=check),indent=2)+'\n',encoding='ascii')
    table('weighted_water','Exclusion using the spatial water profile at $D=4$, $V=2$, $m=2$, $d_w=1$, $d_v=.5$, $A_{\\max}=1.8$, $R=4$, $B=.45$. A positive bound on each cell encloses the continuous operator; a midpoint eigenvalue alone would not give this bound.',
          ['Cells/patch','$a_{\\min}\\geq$','$\\rho(\\mathcal S)\\leq$','Scalar margin $\\leq$','Spatial test'],
          [[str(r['cells_per_patch']),decimal_display(r['minimum_a_lower'],7),
            decimal_display(r['cw_upper'],8,True),decimal_display(r['scalar_margin_upper'],8,True),r['weighted_decision']] for r in rows])
    return {'weighted_water':rows},dict(weighted_water_checks=check)


def broad_study():
    from validated_broad_kernel import broad_kernel_certificate,broad_kernel_self_check
    rows=[]
    for D,widths,w in [('4',('5','6','8','10'),'87/100'),('6',('7','8','10','14'),'29/20')]:
        rows.extend(broad_kernel_certificate(D,'2',width,w) for width in widths)
    anchors=[r for r in rows if (r['D'],r['sigma_anchor']) in [('4','5'),('6','7')]]
    table('broad_kernel','Certified width thresholds for broad Gaussian kernels, computed in exact rational arithmetic. Each row proves that two patches uniquely maximise spectral loss for every integer $m\\geq2$ and every real $\\sigma\\geq\\sigma_0$. The thresholds need not be transition points.',
          ['$D$','$\\sigma_0$','$w$','$F_w(\\sigma_0)\\leq$','$\\delta_3\\geq$','Margin $\\geq$'],
          [[r['D'],r['sigma_anchor'],r['sqrt_variance_upper'],rational_display(r['sufficient_bound_upper'],8,True),
            rational_display(r['moment_gap_all_m_ge3'],8),rational_display(r['strict_margin'],8)] for r in anchors])
    return {'broad_kernel':rows},dict(broad_kernel_checks=broad_kernel_self_check())


def rank_study():
    # Imports are local so the two other focused studies can run separately.
    from gaussian_rank_trial import prepare_rank_trial
    from validated_gaussian_rank import gaussian_rank_certificate,gaussian_rank_self_check
    rows=[];vectors=[];audits=[]
    for D,ranks in [('4',(20,30,40)),('6',(20,30,40)),('14',(96,112,128))]:
        for p in ranks:
            trial,diagnostic=prepare_rank_trial(D,p,polish_digits=50)
            record,audit=gaussian_rank_certificate(D,p,trial,precision=80)
            rows.append(dict(**record,even_principal_float=diagnostic['even_principal_float'],
                odd_principal_float=diagnostic['odd_principal_float'],even_second_float=diagnostic['even_second_float'],
                even_trial_iterations=diagnostic['even_trial']['iterations'],odd_trial_iterations=diagnostic['odd_trial']['iterations']))
            vectors.append(dict(D=D,p=p,precision=80,trial=trial));audits.append(audit)
            print(f'finite-rank D={D}, p={p}: certified',flush=True)
    (DATA/'gaussian_rank_vectors.json').write_text(json.dumps(vectors,indent=2)+'\n',encoding='ascii')
    (DATA/'gaussian_rank_audits.json').write_text(json.dumps(audits,indent=2)+'\n',encoding='ascii')
    checks=[gaussian_rank_self_check(v['D'],v['p'],v['trial'],precision=80)
            for v in vectors if (v['D'],v['p']) in [('6',40),('14',128)]]
    (DATA/'gaussian_rank_checks.json').write_text(json.dumps(checks,indent=2)+'\n',encoding='ascii')
    table('gaussian_rank','Finite-rank enclosures of the continuous Gaussian envelope spectrum. The full gap is $g=\\rho_1-\\lambda_2$; the fragmentation gap is $\\gamma=(V/D)g$. Widths include both finite-matrix arithmetic and the analytic positive tail.',
          ['$D$','$p$','Tail $\\leq$','$\\rho_1\\geq$','$\\lambda_2\\leq$','Gap width $\\leq$'],
          [[r['D'],str(r['features']),scientific_upper(r['feature_tail_upper']),
            decimal_display(r['rho_lower'],10),decimal_display(r['second_upper'],10,True),
            scientific_upper(r['gap_width_upper'])] for r in rows])
    return {'gaussian_rank':rows},dict(gaussian_rank_checks=checks)


def make_figure():
    from reportlab.pdfgen import canvas
    from reportlab.lib import colors
    blue,orange,green=(colors.HexColor(v) for v in ('#1f77b4','#d95f02','#228833'))
    c=canvas.Canvas(str(FIG/'spatial_broad_rank.pdf'),pagesize=(640,510))
    weighted=read_rows('weighted_water');broad=read_rows('broad_kernel')
    plot(c,(0,255,320,255),'(a) Spatial-water certificate','Cells per patch','Continuous radius upper',
         [('Majorant',[int(r['cells_per_patch']) for r in weighted],[float(r['cw_upper']) for r in weighted],blue),
          ('Threshold',[2,32],[1,1],orange)],True,xticks=[2,4,8,16,32],legend_location='above')
    series=[]
    for D,anchor,col in [('4',5,blue),('6',7,orange)]:
        rr=[r for r in broad if r['D']==D]
        series.append(('D='+D,[float(Fraction(r['sigma_anchor']))/anchor for r in rr],
                       [float(Fraction(r['sufficient_bound_upper'])/Fraction(r['moment_gap_all_m_ge3'])) for r in rr],col))
    plot(c,(320,255,320,255),'(b) Uniform broad-kernel bound','Width / anchor width','F / moment gap',
         series,xticks=[1,1.25,1.5,1.75,2],legend_location='above',ylim=(0,1))
    rank_path=DATA/'gaussian_rank.csv'
    if rank_path.exists():
        rank=read_rows('gaussian_rank')
        for box,Dlist,title in [((0,0,320,255),['4','6'],'(c) Continuous gap widths'),
                                ((320,0,320,255),['14'],'(d) Larger-envelope certificate')]:
            plot(c,box,title,'Feature rank p','Full gap interval width',
                 [('D='+D,[int(r['features']) for r in rank if r['D']==D],
                   [float(r['gap_width_upper']) for r in rank if r['D']==D],col)
                  for D,col in zip(Dlist,(blue,orange))],False,True,legend_location='above')
    c.save()


def main(parts=('weighted','broad','rank')):
    experiments={};updates={}
    for part in parts:
        result,checks={'weighted':weighted_study,'broad':broad_study,'rank':rank_study}[part]()
        experiments.update(result);updates.update(checks)
    for name,rows in experiments.items():csvfile(name,rows)
    path=ROOT/'output/pdf/shape_spectral_results.csv'
    with path.open(newline='',encoding='utf-8') as stream:
        combined=[r for r in csv.DictReader(stream) if r['experiment'] not in experiments]
    for name,rows in experiments.items():combined.extend(dict(experiment=name,**row) for row in rows)
    fields=list(dict.fromkeys(key for row in combined for key in row))
    with path.open('w',newline='',encoding='utf-8') as stream:
        writer=csv.DictWriter(stream,fieldnames=fields);writer.writeheader();writer.writerows(combined)
    summary=json.loads((DATA/'summary.json').read_text())
    summary.update(updates,experiment_rows=len(combined),numerical_experiment_count=len({r['experiment'] for r in combined}))
    for name,rows in experiments.items():summary[name+'_rows']=len(rows)
    (DATA/'summary.json').write_text(json.dumps(summary,indent=2)+'\n',encoding='ascii')
    if all((DATA/(name+'.csv')).exists() for name in ('weighted_water','broad_kernel','gaussian_rank')):make_figure()
    print(json.dumps(dict(extension_rows={k:len(v) for k,v in experiments.items()},result_rows=len(combined)),indent=2))
    if set(parts)=={'weighted','broad','rank'}:
        from coupled_optimum_study import main as coupled_optimum_main
        coupled_optimum_main()


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--parts',nargs='+',choices=['weighted','broad','rank'],default=['weighted','broad','rank'])
    main(parser.parse_args().parts)
