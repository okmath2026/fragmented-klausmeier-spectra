"""Exact-rational certificates for a whole broad-Gaussian parameter half-line.

No floating-point eigenvalue, pi approximation, exponential evaluation or
finite scan over patch counts enters this certificate.  The implemented
sufficient condition comes from exact geometric moments, a rank-one Schur
estimate on the two-patch operator, and monotonicity of a rational majorant.
It proves ordering of the continuous integral operators, not of sampled
matrices.  It is a sufficient width bound, not an exact transition location.
"""
from decimal import localcontext, ROUND_CEILING
from fractions import Fraction
from math import isqrt

if not __debug__:
    raise RuntimeError("Run validated certificates without -O: assertion checks are required.")


def _rational(value, name):
    if isinstance(value, bool) or not isinstance(value, (str, int, Fraction)):
        raise TypeError(name + " must be an exact rational string, integer or Fraction")
    try:
        return Fraction(value)
    except (ValueError, ZeroDivisionError) as exc:
        raise ValueError(name + " must specify a finite rational number") from exc


def _sqrt_rational_upper(value, digits=12):
    """An exact rational upper bound, checked by integer squaring."""
    if value < 0:
        raise ValueError("a nonnegative square-root argument is required")
    scale = 10 ** digits
    numerator = value.numerator * scale * scale
    denominator = value.denominator
    root = isqrt(numerator // denominator)
    if root * root * denominator < numerator:
        root += 1
    upper = Fraction(root, scale)
    assert upper * upper >= value
    return upper


def equal_patch_second_moment(D_string, V_string, m):
    """Exact variance of uniform measure on the centred equal-patch family."""
    D, V = _rational(D_string, "D"), _rational(V_string, "V")
    if not D > V > 0:
        raise ValueError("requires D>V>0")
    if not isinstance(m, int) or isinstance(m, bool) or m < 2:
        raise ValueError("m must be an integer at least two")
    length = V / m
    centre_step = (D * m - V) / (m * (m - 1))
    return centre_step * centre_step * (m * m - 1) / 12 + length * length / 12


def broad_kernel_certificate(D_string, V_string, sigma_string,
                             sqrt_variance_upper=None):
    """Prove m=2 uniquely maximises beta for all sigma>=the supplied anchor.

    D_string,V_string,sigma_string are exact rational geometry/width strings.
    A supplied rational square-root upper bound is checked exactly.  Otherwise
    a rational ceiling to twelve decimal places is generated by integer
    arithmetic.  The output contains rational strings only, plus metadata.

    A nonpositive Schur denominator or nonpositive strict margin raises an
    ArithmeticError.  Such a failure is inconclusive and does not assert that
    m=2 ceases to be optimal.  The theorem covers every integer m>=3 without
    evaluating any fragment eigenvalue and every real sigma>=sigma_anchor.
    """
    if not all(isinstance(value, str) for value in
               (D_string, V_string, sigma_string)):
        raise TypeError("D, V and sigma must be exact rational strings")
    D = _rational(D_string, "D")
    V = _rational(V_string, "V")
    sigma = _rational(sigma_string, "sigma")
    if not D > V > 0 or sigma <= 0:
        raise ValueError("requires D>V>0 and sigma>0")
    outer, inner = D / 2, (D - V) / 2
    s2 = (outer ** 3 - inner ** 3) / (3 * (outer - inner))
    s4 = (outer ** 5 - inner ** 5) / (5 * (outer - inner))
    variance = s4 - s2 * s2
    assert variance > 0
    sqrt_upper = (_sqrt_rational_upper(variance) if sqrt_variance_upper is None
                  else _rational(sqrt_variance_upper, "sqrt_variance_upper"))
    if sqrt_upper <= 0 or sqrt_upper * sqrt_upper < variance:
        raise ValueError("the supplied rational does not enclose sqrt(s4-s2^2) from above")
    A4 = (2 * s4 + 6 * s2 * s2) / 8
    B4 = (outer ** 4 + 6 * outer * outer * s2 + s4) / 8
    T = s2 + D * D / 2
    delta3 = (D - V) * (3 * D - 2 * V) / 36
    denominator = sigma * sigma - T
    if denominator <= 0:
        raise ArithmeticError("the rank-one Schur denominator is not strictly positive")
    bound = A4 / (sigma * sigma) + (sqrt_upper / 2 + B4 / (sigma * sigma)) ** 2 / denominator
    margin = delta3 - bound
    if margin <= 0:
        raise ArithmeticError("the broad-kernel sufficient ordering condition is inconclusive")
    # Each positive summand in the bound decreases with real sigma whenever
    # sigma^2>T.  The exact all-m moment gap is bounded below by delta3.
    return dict(D=str(D), V=str(V), sigma_anchor=str(sigma),
        two_patch_second_moment=str(s2), two_patch_fourth_moment=str(s4),
        variance_x_squared=str(variance), sqrt_variance_upper=str(sqrt_upper),
        A4=str(A4), B4=str(B4), T=str(T),
        schur_denominator_numerator_lower=str(denominator),
        moment_gap_all_m_ge3=str(delta3), sufficient_bound_upper=str(bound),
        strict_margin=str(margin), beta_gap_rational_coefficient_lower=str(V * margin),
        first_competing_m=3, unique_maximizer_m=2,
        all_m_ge3=True, all_sigma_ge_anchor=True,
        arithmetic="exact Fraction arithmetic; integer-verified square-root upper bound",
        method="uniform second-moment gap; rank-one Schur bound; decreasing width majorant")


def broad_kernel_self_check():
    """Exact algebra/endpoint regression, separate from the analytic coverage."""
    cases = [("4", "2", "5", "87/100", Fraction(8971121, 33000000)),
             ("6", "2", "7", "29/20", Fraction(833575121, 852835200)),
             ("11/3", "7/5", "8", None, None)]
    for D_string, V_string, sigma_string, sqrt_upper, saved_bound in cases:
        record = broad_kernel_certificate(D_string, V_string, sigma_string, sqrt_upper)
        D, V = Fraction(D_string), Fraction(V_string)
        s2 = Fraction(record["two_patch_second_moment"])
        delta3 = Fraction(record["moment_gap_all_m_ge3"])
        assert equal_patch_second_moment(D_string, V_string, 2) == s2
        if saved_bound is not None:
            assert Fraction(record["sufficient_bound_upper"]) == saved_bound
        for m in range(2, 18):
            gap = s2 - equal_patch_second_moment(D_string, V_string, m)
            explicit = ((D - V) * (m - 2) * (m * (2 * D - V) - V)
                        / (12 * m * (m - 1)))
            assert gap == explicit
            if m >= 3:
                excess = ((D - V) * (m - 3) * ((3 * D - V) * m - 2 * V)
                          / (36 * m * (m - 1)))
                assert gap - delta3 == excess and excess >= 0
        doubled = broad_kernel_certificate(D_string, V_string,
                                           str(2 * Fraction(sigma_string)), sqrt_upper)
        assert Fraction(doubled["sufficient_bound_upper"]) < Fraction(record["sufficient_bound_upper"])
        with localcontext() as alien:
            alien.prec = 2
            alien.rounding = ROUND_CEILING
            assert broad_kernel_certificate(D_string, V_string, sigma_string, sqrt_upper) == record
    # Deliberately incorrect upper-root metadata must be rejected.
    try:
        broad_kernel_certificate("4", "2", "5", "1/10")
    except ValueError:
        pass
    else:
        raise AssertionError("an invalid square-root upper bound was accepted")
    return dict(exact_rational_anchor_regression=True,
        exact_moment_identity_checks=True, exact_uniform_gap_factorisation_checks=True,
        dyadic_width_consistency=True, ambient_decimal_context_invariance=True,
        invalid_root_bound_rejected=True,
        all_integer_and_width_coverage="analytic inequalities, not a finite numerical scan")
